def _clear_ram_cache():
    for k in LCA._cache:
        LCA._cache[k] = None
    get_cache_paths.cache_clear()


@pytest.fixture(autouse=True)
def _manage_lca_cache():
    _clear_ram_cache()
    yield
    _clear_ram_cache()
    if _OUTPUT_FILE.exists():
        os.remove(_OUTPUT_FILE)


def test_monte_carlo_pipeline_matches_seed42_reference():
    np.random.seed(_SEED)
    mc = Monte_Carlo_Analysis(str(_INPUT_FILE))
    np.testing.assert_allclose(mc.results, _REFERENCE_RESULTS, rtol=1e-5)
