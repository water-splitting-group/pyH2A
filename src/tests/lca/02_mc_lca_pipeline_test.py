def _clear_ram_cache():
    for k in LCA._cache:
        LCA._cache[k] = None
    get_cache_paths.cache_clear()


@pytest.fixture(autouse=True)
def _manage_lca_cache():
    # RAM cache is process-wide and not keyed by matrix folder, so it must be
    # cleared to avoid reusing another folder's cached matrices. The on-disk
    # Initial_Artifacts cache is intentionally left alone: this test targets
    # the same smartphone_3layer_ced_base folder as 01_gt_e2e_3layer_ced.py,
    # so if that test already populated it, load_all_from_disk_to_ram reuses
    # it and skips the LU factorization.
    _clear_ram_cache()
    yield
    _clear_ram_cache()
    if _OUTPUT_FILE.exists():
        os.remove(_OUTPUT_FILE)


def test_monte_carlo_pipeline_matches_seed42_reference():
    np.random.seed(_SEED)
    mc = Monte_Carlo_Analysis(str(_INPUT_FILE))
    np.testing.assert_allclose(mc.results, _REFERENCE_RESULTS, rtol=1e-5)
